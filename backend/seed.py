"""Create fixed, synthetic demonstration observations."""
import os, sqlite3
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
DB=Path(os.getenv("SKILLSIGHT_DB", ROOT/"data"/"skillsight.db"))
OCC=[("NCO-DEMO-01","Solar PV technician","Renewable energy"),("NCO-DEMO-02","Healthcare assistant","Healthcare"),("NCO-DEMO-03","Data entry operator","Digital services"),("NCO-DEMO-04","Food processing operator","Food processing"),("NCO-DEMO-05","EV service technician","Automotive")]
AREAS=[("Karnataka","Bengaluru Urban"),("Karnataka","Mysuru"),("Maharashtra","Pune"),("Maharashtra","Nagpur"),("Odisha","Khordha"),("Odisha","Cuttack")]

def connect():
 DB.parent.mkdir(parents=True,exist_ok=True)
 c=sqlite3.connect(DB);c.row_factory=sqlite3.Row
 c.executescript((ROOT/"backend"/"schema.sql").read_text(encoding="utf-8"));return c

def seed(reset=False):
 c=connect()
 if reset:
  synthetic=c.execute("SELECT COUNT(*) FROM sources WHERE is_synthetic=1").fetchone()[0]
  total=c.execute("SELECT COUNT(*) FROM sources").fetchone()[0]
  if synthetic!=total:raise RuntimeError("Refusing reset: database contains non-demo sources.")
  c.execute("DELETE FROM scenarios");c.execute("DELETE FROM observations");c.execute("DELETE FROM sources");c.commit()
 if c.execute("SELECT COUNT(*) FROM observations").fetchone()[0]==0:
  sid=c.execute("INSERT INTO sources(name,source_type,access_method,is_synthetic,reporting_note) VALUES(?,?,?,?,?)",("SkillSight fixed demo fixture","synthetic_demo","committed deterministic fixture",1,"Synthetic demonstration data — not official government statistics.")).lastrowid
  rows=[]
  for mi in range(12):
   period=f"2025-{mi+1:02}"
   for ai,(state,district) in enumerate(AREAS):
    for oi,(code,title,sector) in enumerate(OCC):
     base=[34,51,42,29,38][oi]+ai*4;slope=[2,0,-1,1,2][oi]
     demand=max(3,base+slope*mi+((mi*3+oi+ai)%7)-3);seats=[23,65,58,37,31][oi]+(ai%3)*8
     rows.append((sid,period,state,district,sector,code,title,demand,seats,"Synthetic demonstration; generated by fixed formula."))
  c.executemany("INSERT INTO observations(source_id,period,state,district,sector,occupation_code,occupation_title,demand_count,training_seats,quality_note) VALUES(?,?,?,?,?,?,?,?,?,?)",rows);c.commit()
 c.close()

if __name__=="__main__":
 import argparse
 p=argparse.ArgumentParser();p.add_argument("--reset",action="store_true");a=p.parse_args();seed(a.reset);print(f"Demo database ready: {DB}")
